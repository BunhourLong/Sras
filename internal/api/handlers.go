// maxBodyBytes caps a request body.
const maxBodyBytes = 1 << 20 // 1 MB

// handleGetDocument serves GET /db/{collection}/{id}.
func (s *Server) handleGetDocument(w http.ResponseWriter, r *http.Request) {
	doc, err := s.docs.Get(r.Context(), r.PathValue("collection"), r.PathValue("id"))
	if err != nil {
		s.writeServiceError(w, r, err)
		return
	}
	s.writeJSON(w, http.StatusOK, doc)
}

// decodeDocument reads the body as a JSON object; the size is capped by the
// body-limit middleware. Anything else is a 400. Used by both
// document-writing handlers.
func (s *Server) decodeDocument(w http.ResponseWriter, r *http.Request) (service.Document, bool) {
	var doc service.Document
	if err := json.NewDecoder(r.Body).Decode(&doc); err != nil {
		s.writeError(w, http.StatusBadRequest, codeBadRequest, "body must be a JSON object")
		return nil, false
	}
	return doc, true
}

// handlePutDocument serves PUT /db/{collection}/{id}: 201 on create, 200 on
// replace.
func (s *Server) handlePutDocument(w http.ResponseWriter, r *http.Request) {
	doc, ok := s.decodeDocument(w, r)
	if !ok {
		return
	}
	saved, created, err := s.docs.Put(r.Context(), r.PathValue("collection"), r.PathValue("id"), doc)
	if err != nil {
		s.writeServiceError(w, r, err)
		return
	}
	status := http.StatusOK
	if created {
		status = http.StatusCreated
	}
	s.writeJSON(w, status, saved)
}

// handleCreateDocument serves POST /db/{collection}: the id is generated by
// the server, and the saved document comes back with 201 and a Location
// header pointing at it.
func (s *Server) handleCreateDocument(w http.ResponseWriter, r *http.Request) {
	doc, ok := s.decodeDocument(w, r)
	if !ok {
		return
	}
	collection := r.PathValue("collection")
	saved, err := s.docs.Create(r.Context(), collection, doc)
	if err != nil {
		s.writeServiceError(w, r, err)
		return
	}
	id, _ := saved[service.FieldID].(string) // Put always sets it
	w.Header().Set("Location", "/db/"+collection+"/"+id)
	s.writeJSON(w, http.StatusCreated, saved)
}

// handleDeleteDocument serves DELETE /db/{collection}/{id}: 204 on success. An
// optional revision precondition comes from ?rev=N or If-Match: "N".
func (s *Server) handleDeleteDocument(w http.ResponseWriter, r *http.Request) {
	var rev *int64
	v := r.URL.Query().Get("rev")
	if v == "" {
		v = strings.Trim(r.Header.Get("If-Match"), `"`)
	}
	if v != "" {
		n, err := strconv.ParseInt(v, 10, 64)
		if err != nil || n < 0 {
			s.writeError(w, http.StatusBadRequest, codeBadRequest, "rev must be a non-negative integer")
			return
		}
		rev = &n
	}
	if err := s.docs.Delete(r.Context(), r.PathValue("collection"), r.PathValue("id"), rev); err != nil {
		s.writeServiceError(w, r, err)
		return
	}
	w.WriteHeader(http.StatusNoContent)
}

// handleHealthz serves GET /healthz.
func (s *Server) handleHealthz(w http.ResponseWriter, r *http.Request) {
	s.writeJSON(w, http.StatusOK, map[string]string{"status": "ok"})
}

//go:embed openapi.yaml
var openAPISpec []byte

// handleOpenAPI serves GET /openapi.yaml.
func handleOpenAPI(w http.ResponseWriter, r *http.Request) {
	w.Header().Set("Content-Type", "application/yaml")
	_, _ = w.Write(openAPISpec)
}

// docsPage renders Swagger UI against /openapi.yaml.
// ponytail: Swagger UI comes from a CDN, so /docs needs internet; vendor it if that matters.
const docsPage = `<!doctype html>
<html><head><meta charset="utf-8"><title>Sras API</title>
<link rel="stylesheet" href="https://cdn.jsdelivr.net/npm/swagger-ui-dist@5/swagger-ui.css">
</head><body><div id="ui"></div>
<script src="https://cdn.jsdelivr.net/npm/swagger-ui-dist@5/swagger-ui-bundle.js"></script>
<script>SwaggerUIBundle({url: "/openapi.yaml", dom_id: "#ui"})</script>
</body></html>`

// handleDocs serves GET /docs.
func handleDocs(w http.ResponseWriter, r *http.Request) {
	w.Header().Set("Content-Type", "text/html; charset=utf-8")
	_, _ = w.Write([]byte(docsPage))
}
